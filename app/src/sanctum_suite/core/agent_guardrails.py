#!/usr/bin/env python3

import os
import json
import logging
from pathlib import Path
from typing import Dict, Any, List, Optional
from datetime import datetime

logging.basicConfig(
    level=logging.INFO,
    format="%(asctime)s [%(levelname)s] (AgentGuardrails): %(message)s"
)
logger = logging.getLogger("AgentGuardrails")

class AgentSecurityViolationError(Exception):
    """Custom exception raised when an agent action violates safety guardrails."""
    pass

class AutonomousAgentGuardrails:
    """
    Enforces strict security guardrails, syntax validation, and self-correction 
    loops for autonomous agent actions and generated rules within Sanctum Suite.
    """

    def __init__(self, workspace_dir: Path = Path("/var/lib/sanctum")):
        self.workspace_dir = Path(workspace_dir)
        self.workspace_dir.mkdir(parents=True, exist_ok=True)
        logger.info("Inicjalizacja AutonomousAgentGuardrails – strażnik bezpieczeństwa agentów.")

    def validate_generated_rule_syntax(self, rule_content: str, rule_type: str = "yara") -> Dict[str, Any]:
        """
        Validates the syntax and safety parameters of a rule generated by an autonomous agent.
        """
        logger.info(f"Walidacja reguły typu {rule_type} wygenerowanej przez agenta...")
        
        if not rule_content or len(rule_content.strip()) < 10:
            return {
                "valid": False,
                "error": "Generated rule content is empty or too short."
            }

        # Podstawowe sprawdzenie bezpieczeństwa (brak niebezpiecznych wzorców)
        forbidden_patterns = ["rm -rf /", ":(){ :|:& };:", "dd if=/dev/zero"]
        for pattern in forbidden_patterns:
            if pattern in rule_content:
                logger.error(f"Wykryto niedozwolony wzorzec w kodzie wygenerowanym przez agenta: {pattern}")
                raise AgentSecurityViolationError(f"Security guardrail triggered: forbidden pattern '{pattern}' found.")

        # Specyficzna walidacja YARA / Falco
        if rule_type.lower() == "yara" and "rule " not in rule_content:
            return {
                "valid": False,
                "error": "Invalid YARA rule structure: missing 'rule' keyword."
            }

        logger.info("Walidacja reguły zakończona pomyślnie. Brak naruszeń bezpieczeństwa.")
        return {
            "valid": True,
            "checked_at": datetime.utcnow().isoformat() + "Z",
            "rule_type": rule_type
        }

    def enforce_action_boundary(self, action_name: str, parameters: Dict[str, Any]) -> bool:
        """
        Decides whether an autonomous agent action is permitted under current air-gapped policies.
        """
        logger.info(f"Sprawdzanie uprawnień dla akcji agenta: '{action_name}'")
        
        restricted_actions = ["total_system_wipe", "kernel_module_unload", "firewall_disable"]
        
        if action_name in restricted_actions:
            # Sprawdzenie, czy aktywny jest operator override
            override_flag = self.workspace_dir / "operator_override.lock"
            if not override_flag.exists():
                logger.warning(f"Akcja {action_name} zablokowana przez strażnika! Wymagana blokada nadzoru operatora.")
                return False

        return True